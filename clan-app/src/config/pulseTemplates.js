/**
 * ════════════════════════════════════════════════════════════
 *  قوالب الإشعار — سؤال بصفر توكن
 * ════════════════════════════════════════════════════════════
 *
 *  فكرة المستخدم، وهي موفّرة فعلاً:
 *
 *    بدل أن ينادي الخادم Gemini ليكتب "خلصت الكيميا؟" (~640 توكن)
 *    ثم يتجاهله المستخدم، نكتب السؤال من قالب برمجي بصفر تكلفة.
 *    النموذج لا يُنادى إلا حين يضغط "رد" — أي حين نتأكد من الاهتمام.
 *
 *  ️ التنويع ليس رفاهية.
 *     قالب واحد ثابت يصير خلفية بعد ثلاثة أيام ويُتجاهل بصرياً.
 *     خمس صيغ لكل نوع + اختيار شبه عشوائي = إحساس بالحياة
 *     بلا توكن واحد.
 *
 *  ️ النبرة يجب أن تطابق المرافق تماماً.
 *     لو القالب جافّ ثم جاء رد النموذج دافئاً، يشعر المستخدم
 *     بالخياطة — وينكشف أن "الرفيق" آلة.
 */

/** يختار صيغة بثبات نسبي — نفس الحدث يعطي نفس الصيغة */
const pick = (arr, seed = '') => {
  let h = 0;
  for (let i = 0; i < seed.length; i += 1) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  // نضيف اليوم حتى تتغيّر الصيغة بين الأيام لنفس النوع
  const day = Math.floor(Date.now() / 86_400_000);
  return arr[(h + day) % arr.length];
};

// ════════════════════════════════════════════════
//  حسب نوع الحدث
// ════════════════════════════════════════════════

const TASK_DONE = [
  (n) => `عاش يا بطل  خلّصت "${n}" — عاملة إيه معاك؟`,
  (n) => `شفتك خلّصت "${n}"  إيه الأخبار؟`,
  (n) => `"${n}" اتشطبت  طمنّي، إيه اللي حصل فيها؟`,
  (n) => `تمام كده  خلّصت "${n}". فيه حاجة وقفت معاك؟`,
  (n) => `برافو  "${n}" خلصت. حاسس بإيه دلوقتي؟`,
];

/** انتهى الوقت المجدول ولم يقفلها — نسأل بلا افتراض */
const TASK_SCHEDULED_END = [
  (n) => `الوقت خلص لـ "${n}" ⏳ طمنّي عليك، لحقت تخلّصها؟`,
  (n) => `"${n}" كان المفروض تخلص دلوقتي — عامل إيه فيها؟`,
  (n) => `خلص ميعاد "${n}"  إيه اللي وصلتله؟`,
  (n) => `بصّيت لقيت وقت "${n}" عدّى. إيه الموقف؟`,
  (n) => `"${n}" انتهى وقتها ⌛ محتاج نمدّها ولا خلصت؟`,
];

const ALARM_FIRED = [
  () => `صحيت في معادك النهاردة ️ اليوم بادي إزاي؟`,
  () => `صباح الخير  عامل إيه من الصبح؟`,
  () => `شفتك صحيت بدري  إيه خطتك النهاردة؟`,
  () => `يومك بدأ ️ حاسس بإيه؟`,
  () => `صحيان من بدري  نبدأ بإيه؟`,
];

const FOCUS_DONE = [
  (n) => `خلّصت جلسة ${n} دقيقة  عاملة إيه معاك؟`,
  (n) => `${n} دقيقة تركيز خلصت  ركّزت فيهم كويس؟`,
  (n) => `جلستك خلصت  إيه اللي أنجزته؟`,
  (n) => `عاش، ${n} دقيقة كاملة  إيه الأخبار؟`,
  (n) => `الجلسة انتهت  حاسس إنك قدّمت؟`,
];

const WEEK_DUE = [
  () => `الأسبوع قرّب يخلص  تحب نوثّقه سوا؟`,
  () => `وقت التوثيق الأسبوعي ️ إيه أهم حاجة حصلت؟`,
  () => `أسبوع كامل عدّى  نراجعه؟`,
  () => `التوثيق مستنّيك  عامل إيه الأسبوع ده؟`,
  () => `قرب نقفل الأسبوع  إيه اللي اتعلّمته؟`,
];

const BUILDERS = {
  TASK_DONE,
  TASK_SCHEDULED_END,
  ALARM_FIRED,
  FOCUS_DONE,
  WEEK_DUE,
};

/**
 * يبني نصّ إشعار لحدث واحد.
 *
 * @param {string} trigger
 * @param {string} subjectName
 * @returns {string}
 */
export const single = (trigger, subjectName = '') => {
  const list = BUILDERS[trigger] ?? TASK_DONE;
  return pick(list, `${trigger}:${subjectName}`)(subjectName);
};

// ════════════════════════════════════════════════
//  الدمج — عدة أحداث في إشعار واحد
// ════════════════════════════════════════════════

/**
 * صيغ الافتتاح للإشعار المدموج.
 *
 * ️ قرار المستخدم: "لو 3 إشعارات في فترة متقاربة يتدمجوا
 *    في إشعار واحد بعنوان السؤال لكل إشعار".
 *
 *    فالبنية: افتتاحية واحدة + سطر لكل حدث. المستخدم يرى
 *    كل مواضيعه دفعة واحدة بدل ثلاث مقاطعات.
 */
const MERGED_OPENERS = [
  (c) => `شفتك خلّصت ${c} حاجات `,
  (c) => `${c} إنجازات ورا بعض `,
  (c) => `يومك مليان — ${c} حاجات خلصت `,
  (c) => `عاش، ${c} حاجات في وقت قصير `,
];

/** سطر مختصر لكل حدث داخل الإشعار المدموج */
const LINE = {
  TASK_DONE: (n) => `· "${n}" — عاملة إيه؟`,
  TASK_SCHEDULED_END: (n) => `· "${n}" خلص وقتها — إيه الموقف؟`,
  ALARM_FIRED: () => `· صحيت في معادك — اليوم بادي إزاي؟`,
  FOCUS_DONE: (n) => `· جلسة ${n} دقيقة — ركّزت كويس؟`,
  WEEK_DUE: () => `· التوثيق الأسبوعي مستنّيك`,
};

/**
 * يبني إشعاراً واحداً من عدة أحداث.
 *
 * @param {Array<{trigger, subjectName}>} events
 */
export const merged = (events = []) => {
  if (!events.length) return '';
  if (events.length === 1) return single(events[0].trigger, events[0].subjectName);

  const opener = pick(MERGED_OPENERS, String(events.length))(events.length);
  const lines = events
    .map((e) => (LINE[e.trigger] ?? LINE.TASK_DONE)(e.subjectName))
    .join('\n');

  return `${opener}\n${lines}\n\nطمنّي عليك `;
};

/**
 * عنوان قصير للإشعار — يظهر في شريط الإشعارات.
 */
export const title = (events = []) =>
  events.length > 1 ? `المرافق · ${events.length} مواضيع` : 'المرافق';

export default { single, merged, title };
